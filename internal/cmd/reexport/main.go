// Command reexport writes the root giode package's reexport.go: an
// alias for every exported name of package ui, so `giode.Box` and
// `ui.Box` are the same thing and a custom host can import ui without
// the root package's App (and gioui.org/app). Run it through go
// generate in the root package.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"sort"
	"strings"
)

func main() {
	out, err := generate("ui")
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("reexport.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func generate(dir string) ([]byte, error) {
	fset := token.NewFileSet()
	pkgs, err := parser.ParseDir(fset, dir, func(fi os.FileInfo) bool {
		return !strings.HasSuffix(fi.Name(), "_test.go")
	}, parser.ParseComments)
	if err != nil {
		return nil, err
	}
	pkg := pkgs["ui"]
	if pkg == nil {
		return nil, fmt.Errorf("no package ui in %s", dir)
	}
	var names []string
	for name := range pkg.Files {
		names = append(names, name)
	}
	sort.Strings(names)

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/cmd/reexport from package ui; DO NOT EDIT.\n\n")
	b.WriteString("package giode\n\nimport \"github.com/mehran9675/giode/ui\"\n\n")
	src := func(n ast.Node) string {
		var s bytes.Buffer
		printer.Fprint(&s, fset, n)
		return s.String()
	}
	doc := func(g *ast.CommentGroup) {
		if g != nil {
			for _, c := range g.List {
				b.WriteString(c.Text + "\n")
			}
		}
	}
	for _, name := range names {
		for _, decl := range pkg.Files[name].Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if d.Recv != nil || !d.Name.IsExported() {
					continue
				}
				doc(d.Doc)
				if d.Type.TypeParams == nil {
					// A variable needs none of the signature's imports.
					fmt.Fprintf(&b, "var %s = ui.%s\n\n", d.Name.Name, d.Name.Name)
					continue
				}
				// Generic functions can't be values: wrap them.
				fmt.Fprintf(&b, "func %s", d.Name.Name)
				if d.Type.TypeParams != nil {
					b.WriteString("[" + fieldList(src, d.Type.TypeParams) + "]")
				}
				b.WriteString("(" + fieldList(src, d.Type.Params) + ")")
				if d.Type.Results != nil {
					r := fieldList(src, d.Type.Results)
					if len(d.Type.Results.List) > 1 || len(d.Type.Results.List[0].Names) > 0 {
						r = "(" + r + ")"
					}
					b.WriteString(" " + r)
				}
				var args []string
				variadic := false
				for _, f := range d.Type.Params.List {
					if _, ok := f.Type.(*ast.Ellipsis); ok {
						variadic = true
					}
					for _, n := range f.Names {
						args = append(args, n.Name)
					}
				}
				call := strings.Join(args, ", ")
				if variadic {
					call += "..."
				}
				targs := ""
				if d.Type.TypeParams != nil {
					var tn []string
					for _, f := range d.Type.TypeParams.List {
						for _, n := range f.Names {
							tn = append(tn, n.Name)
						}
					}
					targs = "[" + strings.Join(tn, ", ") + "]"
				}
				ret := "return "
				if d.Type.Results == nil {
					ret = ""
				}
				fmt.Fprintf(&b, " {\n\t%sui.%s%s(%s)\n}\n\n", ret, d.Name.Name, targs, call)
			case *ast.GenDecl:
				var specs []string
				for _, spec := range d.Specs {
					switch s := spec.(type) {
					case *ast.TypeSpec:
						if !s.Name.IsExported() {
							continue
						}
						var sb strings.Builder
						if s.Doc != nil && len(d.Specs) > 1 {
							for _, c := range s.Doc.List {
								sb.WriteString(c.Text + "\n")
							}
						}
						sb.WriteString(s.Name.Name)
						args := ""
						if s.TypeParams != nil {
							sb.WriteString("[" + fieldList(src, s.TypeParams) + "]")
							var tn []string
							for _, f := range s.TypeParams.List {
								for _, n := range f.Names {
									tn = append(tn, n.Name)
								}
							}
							args = "[" + strings.Join(tn, ", ") + "]"
						}
						sb.WriteString(" = ui." + s.Name.Name + args)
						specs = append(specs, sb.String())
					case *ast.ValueSpec:
						var exported []string
						for _, n := range s.Names {
							if n.IsExported() {
								exported = append(exported, n.Name)
							}
						}
						if len(exported) == 0 {
							continue
						}
						var sb strings.Builder
						if s.Doc != nil && len(d.Specs) > 1 {
							for _, c := range s.Doc.List {
								sb.WriteString(c.Text + "\n")
							}
						}
						var vals []string
						for _, n := range exported {
							vals = append(vals, "ui."+n)
						}
						sb.WriteString(strings.Join(exported, ", ") + " = " + strings.Join(vals, ", "))
						specs = append(specs, sb.String())
					}
				}
				if len(specs) == 0 {
					continue
				}
				doc(d.Doc)
				kw := d.Tok.String()
				if len(specs) == 1 && len(d.Specs) == 1 {
					b.WriteString(kw + " " + specs[0] + "\n\n")
					continue
				}
				b.WriteString(kw + " (\n")
				for _, s := range specs {
					b.WriteString(s + "\n")
				}
				b.WriteString(")\n\n")
			}
		}
	}
	return format.Source(b.Bytes())
}

// fieldList prints a parameter, result or type parameter list.
func fieldList(src func(ast.Node) string, l *ast.FieldList) string {
	var parts []string
	for _, f := range l.List {
		t := src(f.Type)
		if len(f.Names) == 0 {
			parts = append(parts, t)
			continue
		}
		var ns []string
		for _, n := range f.Names {
			ns = append(ns, n.Name)
		}
		parts = append(parts, strings.Join(ns, ", ")+" "+t)
	}
	return strings.Join(parts, ", ")
}
